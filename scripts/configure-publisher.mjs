import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
const root=new URL('../',import.meta.url);
const vars=await readFile(new URL('.dev.vars',root),'utf8');
const get=name=>vars.match(new RegExp(`^${name}=["']?([^\\r\\n"']+)`, 'm'))?.[1]?.trim();
const githubToken=get('GITHUB_TOKEN'),publishSecret=get('PUBLISH_SECRET');
if(!githubToken?.startsWith('github_pat_')||!publishSecret||publishSecret.length<32)throw Error('Completa .dev.vars con un token fine-grained y una clave de al menos 32 caracteres.');
const check=await fetch('https://api.github.com/repos/artesbuhooficial-max/de-todo-un-poco-bodas/contents/data/content.json',{headers:{authorization:`Bearer ${githubToken}`,accept:'application/vnd.github+json','user-agent':'artes-buho-publisher-setup'}});
if(!check.ok)throw Error('El token no permite leer el contenido del repositorio de esta landing.');
const auth=await readFile(join(process.env.APPDATA,'xdg.config/.wrangler/config/default.toml'),'utf8');
const cloudflareToken=auth.match(/^oauth_token\s*=\s*"([^"]+)"/m)?.[1];
const headers={authorization:`Bearer ${cloudflareToken}`,'content-type':'application/json'};
const url='https://api.cloudflare.com/client/v4/accounts/0426b9932c46913ed8bee6eef9f56577/pages/projects/de-todo-un-poco-bodas';
const current=await fetch(url,{headers}).then(r=>r.json());
if(!current.success)throw Error('No se pudo leer el proyecto de Cloudflare.');
const env_vars={...current.result.deployment_configs.production.env_vars,GITHUB_TOKEN:{type:'secret_text',value:githubToken},PUBLISH_SECRET:{type:'secret_text',value:publishSecret}};
const response=await fetch(url,{method:'PATCH',headers,body:JSON.stringify({deployment_configs:{production:{env_vars}}})});
const result=await response.json();
if(!response.ok||!result.success)throw Error('Cloudflare no permitió guardar los secretos.');
console.log('Secretos cifrados configurados en Production. Activa un nuevo despliegue para usarlos.');
